IF object_id(N'tempdb..#ОсновнаяФронтальнаяВкладка') IS NOT NULL 
    DROP TABLE #ОсновнаяФронтальнаяВкладка;

SELECT 
    f.Номенклатура,
    f.Код,
    f.[Единица измерения],
    f.скт,
    
    two_month.КоличествоСуммарно AS [Количество (в базовых ед.) за текущий месяц -2],
    one_month.КоличествоСуммарно AS [Количество (в базовых ед.) за текущий месяц -1],
    no_month.КоличествоСуммарно  AS [Количество (в базовых ед.) за текущий месяц],
    
    NULL AS [ОСТАТОК план],
    NULL AS [План за текущий месяц -2],
    NULL AS [План за текущий месяц -1],
    NULL AS [План за текущий месяц],
    
    brak_now.КоличествоСуммарно       AS [Остатки "Брак, склады"],
    brak_for_storage.КоличествоСуммарно AS [Остатки "Брак, склады производства"],
    ISNULL(brak_now.КоличествоСуммарно, 0) + ISNULL(brak_for_storage.КоличествоСуммарно, 0) AS [Остатки "Брак"],
    
    NULL AS [Стоимость "Брак" без НДС],
    
    karantin.КоличествоСуммарно  AS [Остатки "Карантин"],
    prigodin.КоличествоСуммарно  AS [Остатки "Пригоден" ССХ],
    material.КоличествоСуммарно  AS [Остатки "Пригоден" в производстве материал],
    libery.КоличествоСуммарно    AS [Остатки "Пригоден" в производстве лаборатория]

INTO #ОсновнаяФронтальнаяВкладка
FROM #остаткиНаСкладах AS f

-- Затраты 2 месяца назад
LEFT JOIN #ЗатратыНаВыпускДваПоследних AS two_month 
    ON two_month.Номенклатура = f.Номенклатура 
   AND two_month.Дата = DATEFROMPARTS(YEAR(GETDATE())-2000, MONTH(GETDATE())-2, 1)

-- Затраты 1 месяц назад
LEFT JOIN #ЗатратыНаВыпускДваПоследних AS one_month 
    ON one_month.Номенклатура = f.Номенклатура 
   AND one_month.Дата = DATEFROMPARTS(YEAR(GETDATE())-2000, MONTH(GETDATE())-1, 1)

-- Затраты текущий месяц
LEFT JOIN #ЗатратыНаВыпуск AS no_month 
    ON no_month.Номенклатура = f.Номенклатура

-- Брак склады
LEFT JOIN #остаткиНаСкладахБрак AS brak_now 
    ON brak_now.Номенклатура = f.Номенклатура

-- Брак производство
LEFT JOIN #остаткиНаСкладахБрак1 AS brak_for_storage 
    ON brak_for_storage.Номенклатура = f.Номенклатура

-- Карантин
LEFT JOIN #остаткиНаСкладахКарантин1 AS karantin 
    ON karantin.Номенклатура = f.Номенклатура

-- Пригоден
LEFT JOIN #остаткиНаСкладахПригоден1 AS prigodin 
    ON prigodin.Номенклатура = f.Номенклатура

-- Материалы в производстве
LEFT JOIN #МатериалыВПроизводствеСегодня AS material 
    ON material.Номенклатура = f.Номенклатура

-- Лаборатория
LEFT JOIN #Лаборатория AS libery 
    ON libery.Номенклатура = f.Номенклатура

WHERE f.скт2 LIKE '%Основное сырье%'
   OR f.скт2 LIKE '%Компоненты%'
   OR f.скт2 LIKE '%Тара и тарные материалы (10.04)%'

GROUP BY 
    f.Номенклатура,
    f.Код,
    f.[Единица измерения],
    f.скт,
    two_month.КоличествоСуммарно,
    one_month.КоличествоСуммарно,
    no_month.КоличествоСуммарно,
    brak_now.КоличествоСуммарно,
    brak_for_storage.КоличествоСуммарно,
    karantin.КоличествоСуммарно,
    prigodin.КоличествоСуммарно,
    material.КоличествоСуммарно,
    libery.КоличествоСуммарно;

