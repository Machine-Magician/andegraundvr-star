    f.[План за текущий месяц],
    f.[Остатки "Брак, склады"],
    f.[Остатки "Брак, склады производства"],
    f.[Остатки "Брак"],
    
    -- Стоимость "Брак"
    m.КоличествоСуммарно * f.[Остатки "Брак"] AS [Стоимость "Брак" без НДС],
    
    f.[Остатки "Карантин"],
    f.[Остатки "Пригоден" ССХ],
    f.[Остатки "Пригоден" в производстве материал] + f.[Остатки "Пригоден" в производстве лаборатория] AS [Остатки "Пригоден" в производстве],
    
    -- Обеспеченность по расходу 2- месяца (с защитой от деления на ноль)
    CASE 
        WHEN (f.[Количество (в базовых ед.) за текущий месяц -2] 
              + f.[Количество (в базовых ед.) за текущий месяц -1] 
              + f.[Количество (в базовых ед.) за текущий месяц]) = 0 
             OR (30 * (
                    CASE WHEN f.[Количество (в базовых ед.) за текущий месяц -2] > 0 THEN 1 ELSE 0 END
                    + CASE WHEN f.[Количество (в базовых ед.) за текущий месяц -1] > 0 THEN 1 ELSE 0 END
                 )
                 + CASE WHEN f.[Количество (в базовых ед.) за текущий месяц] > 0 
                        THEN DATEDIFF(DAY, 
                              DATEFROMPARTS(YEAR(GETDATE())-2000, MONTH(GETDATE()), 1), 
                              EOMONTH(GETDATE()))
                        ELSE 0 
                   END) = 0 
        THEN NULL
        ELSE (f.[Остатки "Пригоден" ССХ] + f.[Остатки "Пригоден" в производстве материал] + f.[Остатки "Пригоден" в производстве лаборатория]) 
             / 
             (
                 (f.[Количество (в базовых ед.) за текущий месяц -2] 
                  + f.[Количество (в базовых ед.) за текущий месяц -1] 
                  + f.[Количество (в базовых ед.) за текущий месяц])
                 /
                 (
                     30 * (
                         CASE WHEN f.[Количество (в базовых ед.) за текущий месяц -2] > 0 THEN 1 ELSE 0 END
                         + CASE WHEN f.[Количество (в базовых ед.) за текущий месяц -1] > 0 THEN 1 ELSE 0 END
                     )
                     + CASE WHEN f.[Количество (в базовых ед.) за текущий месяц] > 0 
                            THEN DATEDIFF(DAY, 
                                  DATEFROMPARTS(YEAR(GETDATE())-2000, MONTH(GETDATE()), 1), 
                                  EOMONTH(GETDATE()))
                            ELSE 0 
                       END
                 )
             )
    END AS [Обеспеченность по расходу 2- месяца],
    
    NULL AS [Обеспеченность потребности 2+ месяца],
    NULL AS [Сколько заказать до 60-дневной обеспеченности],
    NULL AS [Когда сработаем?],
    NULL AS [признак],
    NULL AS [Потребность из заказов],
    
    -- Стоимость "Пригоден"
    (f.[Остатки "Пригоден" ССХ] + f.[Остатки "Пригоден" в производстве материал] + f.[Остатки "Пригоден" в производстве лаборатория]) 
    * m.КоличествоСуммарно AS [Стоимость "Пригоден" ССХ, руб. без НДС],
    
    -- Расход за 2 месяца
    f.[Количество (в базовых ед.) за текущий месяц -2] 
    + f.[Количество (в базовых ед.) за текущий месяц -1] 
    + f.[Количество (в базовых ед.) за текущий месяц] AS [Расход за 2 месяца],
    
    -- Цена (с защитой от деления на ноль)
    CASE 
        WHEN (f.[Остатки "Пригоден" ССХ] + f.[Остатки "Пригоден" в производстве материал] + f.[Остатки "Пригоден" в производстве лаборатория]) = 0 
        THEN NULL
        ELSE (f.[Количество (в базовых ед.) за текущий месяц -2] 
              + f.[Количество (в базовых ед.) за текущий месяц -1] 
              + f.[Количество (в базовых ед.) за текущий месяц]) 
             / (f.[Остатки "Пригоден" ССХ] + f.[Остатки "Пригоден" в производстве материал] + f.[Остатки "Пригоден" в производстве лаборатория])
    END AS цена,
    
    NULL AS [расход, ед.изм/день],
    NULL AS [расход, руб/день],
    NULL AS [расход, ед.изм/день по зак],
    NULL AS [расход, руб/день по зак],
    
    -- Стоимость "Карантин"
    f.[Остатки "Карантин"] * m.КоличествоСуммарно AS [Стоимость "Карантин", руб без НДС],
    
    -- Стоимость всего
    m.КоличествоСуммарно * (
        f.[Остатки "Пригоден" ССХ] 
        + f.[Остатки "Пригоден" в производстве материал] 
        + f.[Остатки "Пригоден" в производстве лаборатория]
        + f.[Остатки "Карантин"]
        + f.[Остатки "Брак"]
    ) AS [Стоимость всего],
    
    NULL AS [Обеспеченность из заказов]

INTO #ОсновнаяФронтальнаяВкладка2лвл
FROM #ОсновнаяФронтальнаяВкладка AS f
LEFT JOIN #Стоимость AS m 
    ON m.Номенклатура = f.Номенклатура;
