 Дирекция
 ,Служба
 ,Отдел
 ,Участок
 ,Территория
 ,CASE 
        -- Если это ночная смена, ВСЕГДА берем дневную смену
        WHEN t.[Вид смены] = 'Ночная смена' THEN 
            COALESCE(
                -- Сначала пытаемся найти дневную смену ТОГО ЖЕ дня
                (
                    SELECT TOP 1 d.Должность 
                    FROM [СлужебнаяДляОтчетов].[dbo].[Численность в смену] d 
                    WHERE d.Сотрудник = t.Сотрудник 
                        AND d.Должность IS NOT NULL 
                        AND d.[Вид смены] = 'Дневная смена'
                        AND d.Месяц = t.Месяц 
                        AND d.День = t.День
                ),
                -- Если нет дневной смены в тот же день, ищем предыдущую
                (
                    SELECT TOP 1 d.Должность 
                    FROM [СлужебнаяДляОтчетов].[dbo].[Численность в смену] d 
                    WHERE d.Сотрудник = t.Сотрудник 
                        AND d.Должность IS NOT NULL 
                        AND d.[Вид смены] = 'Дневная смена'
                        AND d.Месяц = t.Месяц 
                        AND d.День < t.День
                    ORDER BY d.День DESC
                ),
                -- Если вообще не нашли дневную смену, оставляем как есть
                t.Должность
            )
        -- Для дневных смен оставляем как есть
        ELSE t.Должность
   END AS Должность

 ,Сотрудник
 ,[Вид смены]
 ,[Доп.персонал]
 ,[Численность в смену]
 ,день as Рабочий_день
 ,Месяц, convert(nchar(6), 'Неделя')+' '+ convert(nchar(2), 
 datepart(week, datefromparts(year(Месяц), month(месяц), день)) -
 DATEPART(week, DATEADD(month, DATEDIFF(month, 0, datefromparts(year(Месяц), month(месяц), день)), 0))+1) Неделя


 ,Ночные_часы
,case --when Всего_часов=24 then Всего_часов/2
    when (Всего_часов<=11 or (Должность like '%оператор котельной%' and Всего_часов<=12)) and Ночные_часы>0 then Всего_часов 
    when Всего_часов>11 and Должность not like '%оператор котельной%' --and служба not like '%транспортной логистики%' 
and [Вид смены]='Ночная смена' then Всего_часов-11
    when Всего_часов>12 and Должность like '%оператор котельной%' and [Вид смены]='Ночная смена' then Всего_часов-12
  when Всего_часов>11 and Должность not like '%оператор котельной%'  --and служба not like '%транспортной логистики%' 
and [Вид смены]='Дневная смена' and Ночные_часы>0 then 11
  when Всего_часов>12 and Должность like '%оператор котельной%' and [Вид смены]='Дневная смена' and Ночные_часы>0  then 12 
   else Всего_часов end as Часов
 ,case when datepart(dw, datefromparts(year(Месяц), month(Месяц), День))=1 then 'Понедельник' 
   when datepart(dw, datefromparts(year(Месяц), month(Месяц), День))=2 then 'Вторник'
   when datepart(dw, datefromparts(year(Месяц), month(Месяц), День))=3 then 'Среда'
   when datepart(dw, datefromparts(year(Месяц), month(Месяц), День))=4 then 'Четверг'
   when datepart(dw, datefromparts(year(Месяц), month(Месяц), День))=5 then 'Пятница'
   when datepart(dw, datefromparts(year(Месяц), month(Месяц), День))=6 then 'Суббота'
   when datepart(dw, datefromparts(year(Месяц), month(Месяц), День))=7 then 'Воскресенье' 
  end as [День недели]
from [СлужебнаяДляОтчетов].[dbo].[Численность в смену] t
where месяц>='20160101' and Сотрудник like '%саламов д%' and месяц = '2026-01-01' and день = '30'
--and NOT([Вид смены]='Дневная смена' and (Всего_часов<=11 or (Должность like '%оператор котельной%' and Всего_часов<=12)) and Ночные_часы>0)
and NOT (
    [Вид смены] = 'Дневная смена'
    --AND [Должность] LIKE '%Комплектовщик%'
    AND Всего_часов = 11
    AND EXISTS (
        SELECT 1 
        FROM [СлужебнаяДляОтчетов].[dbo].[Численность в смену] n
        WHERE n.Сотрудник = t.Сотрудник
            AND n.Месяц = t.Месяц
            AND n.День = t.День
            AND n.[Вид смены] = 'Ночная смена'
    )
